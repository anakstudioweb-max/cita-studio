export const dictionaries: Record<"en" | "es" | "pt" | "fr", Dict> = {
  en,
  es,
  pt,
  fr,
};

export function resolveLocale(
  stored: string | null,
  acceptLanguage?: string | null,
  navigatorLang?: string | null
): "en" | "es" | "pt" | "fr" {
  if (stored && stored !== "device" && dictionaries[stored as "en"]) {
    return stored as "en" | "es" | "pt" | "fr";
  }
  const raw = (navigatorLang || acceptLanguage || "en").toLowerCase();
  if (raw.startsWith("es")) return "es";
  if (raw.startsWith("pt")) return "pt";
  if (raw.startsWith("fr")) return "fr";
  return "en";
}
